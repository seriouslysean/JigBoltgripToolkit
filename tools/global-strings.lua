-- Generates tests/globalstrings.lua: Blizzard's upper-case enUS global strings, for the test stand-ins to resolve
-- (an unknown global is otherwise a stub table, and text built from it reads "table: 0x...").
-- Source: Ketho/BlizzardInterfaceResources, branch forever, Resources/GlobalStrings/enUS.lua, at the pinned commit.
--   luajit tools/global-strings.lua
local COMMIT = "e230342a476eb4ef484ba7b34adc0da6ecc6acc1"
local url = ("https://raw.githubusercontent.com/Ketho/BlizzardInterfaceResources/%s/Resources/GlobalStrings/enUS.lua"):format(COMMIT)
local source = assert(io.popen("curl -fsS " .. ("%q"):format(url))):read("*a")
assert(source ~= "", "no table from " .. url)

-- The file is Lua assigning globals, some as _G["name"]; run it against a table that stands for _G.
local env = {}
env._G = env
local chunk = assert(loadstring(source))
setfenv(chunk, env)
chunk()

local names = {}
for name, text in pairs(env) do
	if type(text) == "string" and name:find("^%u[%u%d_]*$") then names[#names + 1] = name end
end
table.sort(names)
local out = assert(io.open("tests/globalstrings.lua", "w"))
out:write("-- Generated by tools/global-strings.lua from Ketho/BlizzardInterfaceResources (forever, ", COMMIT, "); never edited by hand.\n")
out:write("-- Blizzard's enUS global strings with upper-case names.\nreturn {\n")
for _, name in ipairs(names) do
	out:write((("\t%s = %q,\n"):format(name, env[name]):gsub("\\\n", "\\n")))
end
out:write("}\n")
out:close()
