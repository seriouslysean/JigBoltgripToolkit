-- Generates tests/deprecated.lua: the functions only Blizzard's Blizzard_Deprecated* addons define, which conformance
-- rejects in a module's calls. The rule is the one the generated header states.
--   lua tools/deprecated.lua <Interface/AddOns dir> <client label, e.g. "1.60.1 (71139)"> [out, default tests/deprecated.lua]
local addons, label, outPath = arg[1], arg[2], arg[3] or "tests/deprecated.lua"
assert(addons and label, "usage: lua tools/deprecated.lua <Interface/AddOns dir> <client label> [out]")

local function lines(command)
	local found = {}
	for line in assert(io.popen(command)):lines() do found[#found + 1] = line end
	return found
end

-- The native functions: every C API the generated docs list, by full name and by bare name, since a global shim
-- named like a native function in any namespace is the client's own.
local native, bare = {}, {}
local here = arg[0]:match("^(.*)/[^/]*$") or "."
for key, fn in pairs(dofile(here .. "/api-docs.lua")(addons).functions) do
	if not fn.scriptObject then native[key], bare[fn.Name] = true, true end
end

-- A definition is a global function, or a global set to a function or to a function's name (a C API, native or
-- not); Mainline-only files never load on Forever. Where several files define one name, the first by path is kept.
local defined = {}
local function define(name, file)
	if not native[name] and not (bare[name] and not name:find(".", 1, true)) and not defined[name] then
		defined[name] = file
	end
end
local files = lines(("cd %q && find Blizzard_Deprecated* -name '*.lua' -not -path '*/Mainline/*' | LC_ALL=C sort"):format(addons))
for _, file in ipairs(files) do
	local source = assert(io.open(addons .. "/" .. file)):read("*a")
	local aliases = {}
	for line in source:gmatch("[^\n]+") do
		local depth = #line:match("^\t*")
		if depth <= 1 then
			local name = line:match("^\t*function%s+([%w_.]+)%s*%(")
				or line:match("^\t*([%a_][%w_.]*)%s*=%s*function%s*%(")
			if name then define(name, file) end
			local alias, target = line:match("^\t*([%a_][%w_.]*)%s*=%s*([%a_][%w_.]*)%s*;?%s*$")
			if alias then aliases[#aliases + 1] = { alias, target } end
		end
	end
	for _, pair in ipairs(aliases) do
		if native[pair[2]] or defined[pair[2]] or pair[2]:find("^C_[%w_]+%.[%w_]+$") then define(pair[1], file) end
	end
end

local names = {}
for name in pairs(defined) do names[#names + 1] = name end
table.sort(names)
local out = assert(io.open(outPath, "w"))
out:write([[
-- Functions that exist only in Blizzard's Blizzard_Deprecated* addons: each is a shim that returns early unless the
-- loadDeprecationFallbacks CVar is on, so a call from an addon is nil on a player's client (IsPlayerSpell is the usual one).
-- Source: Gethe/wow-ui-source, branch forever, Interface/AddOns/Blizzard_Deprecated*, at ]], label, [[. Taken: a top-level
-- function or alias defined there, outside the Mainline-only files, whose name Blizzard_APIDocumentationGenerated does not
-- list as a native function. Each name maps to the file that defines it. Generated by tools/deprecated.lua.
return {
]])
for _, name in ipairs(names) do
	out:write(("\t[%q] = %q,\n"):format(name, defined[name]))
end
out:write("}\n")
out:close()
